/// Resolves a preset by [id], falling back to `Default Dark`.
SshTerminalThemePreset sshTerminalThemeById(String id) =>
    sshTerminalThemes.firstWhere(
      (t) => t.id == id,
      orElse: () => sshTerminalThemes.first,
    );
